-- Run this SQL in the Supabase SQL Editor to create the table used by FlightStatusForm.
create table if not exists public.flights (
    id bigint generated by default as identity primary key,
    flight_number text not null unique,
    destination text not null,
    status text not null default 'On Time',
    created_at timestamptz not null default now()
);

alter table public.flights enable row level security;

drop policy if exists "Allow public flight reads" on public.flights;
create policy "Allow public flight reads"
on public.flights for select
to anon, authenticated
using (true);

drop policy if exists "Allow public flight writes" on public.flights;
create policy "Allow public flight writes"
on public.flights for all
to anon, authenticated
using (true)
with check (true);
