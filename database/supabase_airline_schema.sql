create or replace function public.ensure_flight_seats(p_flight_id bigint)
returns void
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
begin
  if not exists (select 1 from public.flights where id = p_flight_id) then
    raise exception 'Flight not found';
  end if;
  insert into public.seats (flight_id, seat_number, row_number, column_letter, seat_class)
  select p_flight_id, row_number::text || col, row_number, col, seat_class
  from generate_series(1, 20) as rows(row_no)
  cross join unnest(array['A','B','C','D','E','F']) as cols(col)
  cross join lateral (
    select case
      when row_no <= 2 then 'First Class'
      when row_no <= 5 then 'Business'
      else 'Economy'
    end as seat_class
  ) class_for_row
  where not (row_no <= 2 and col in ('C','D'))
  on conflict (flight_id, seat_number) do nothing;
end;
$$;

create or replace function public.create_airline_booking(
  p_flight_id bigint,
  p_travel_class text,
  p_passengers jsonb,
  p_payment_method text,
  p_custom_discount numeric default 0
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, extensions, pg_temp
as $$
declare
  flight_row public.flights%rowtype;
  passenger jsonb;
  seat_row public.seats%rowtype;
  selected_count integer;
  pnr_value text;
  booking_row public.bookings%rowtype;
  base_fare_value numeric(10,2);
  tax_value numeric(10,2);
  discount_value numeric(10,2);
  total_value numeric(10,2);
  transaction_value text;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_travel_class not in ('Economy', 'Business', 'First Class') then raise exception 'Invalid travel class'; end if;
  if p_payment_method not in ('Credit Card', 'Debit Card', 'UPI', 'Net Banking') then raise exception 'Invalid payment method'; end if;
  if jsonb_typeof(p_passengers) <> 'array' or jsonb_array_length(p_passengers) = 0 then raise exception 'At least one passenger is required'; end if;
  if (select count(distinct value ->> 'seatNumber') from jsonb_array_elements(p_passengers)) <> jsonb_array_length(p_passengers) then
    raise exception 'Duplicate seats selected';
  end if;

  select * into flight_row from public.flights where id = p_flight_id for update;
  if not found or flight_row.departure_time is null then raise exception 'Flight not found'; end if;
  if flight_row.status <> 'SCHEDULED' then raise exception 'Flight is not available for booking'; end if;
  if flight_row.available_seats < jsonb_array_length(p_passengers) then raise exception 'Not enough available seats'; end if;

  perform public.ensure_flight_seats(p_flight_id);
  for passenger in select value from jsonb_array_elements(p_passengers)
  loop
    select * into seat_row from public.seats
    where flight_id = p_flight_id and seat_number = passenger ->> 'seatNumber'
    for update;
    if not found then raise exception 'Selected seat does not exist'; end if;
    if seat_row.is_occupied or seat_row.is_blocked then raise exception 'Selected seat is unavailable'; end if;
  end loop;

  base_fare_value := round(
    (case p_travel_class
      when 'Business' then flight_row.business_fare
      when 'First Class' then flight_row.first_class_fare
      else flight_row.economy_fare
    end) * jsonb_array_length(p_passengers), 2
  );
  tax_value := round(base_fare_value * 0.18, 2);
  discount_value := least(greatest(coalesce(p_custom_discount, 0), 0), base_fare_value + tax_value);
  total_value := round(base_fare_value + tax_value - discount_value, 2);

  loop
    pnr_value := upper(substr(encode(extensions.gen_random_bytes(6), 'hex'), 1, 6));
    exit when not exists (select 1 from public.bookings where pnr = pnr_value);
  end loop;
  transaction_value := 'TXN-' || gen_random_uuid()::text;

  insert into public.bookings
    (pnr, user_id, flight_id, total_fare, base_fare, tax_amount, discount_amount, travel_class)
  values
    (pnr_value, auth.uid(), p_flight_id, total_value, base_fare_value, tax_value, discount_value, p_travel_class)
  returning * into booking_row;

  for passenger in select value from jsonb_array_elements(p_passengers)
  loop
    select * into seat_row from public.seats
    where flight_id = p_flight_id and seat_number = passenger ->> 'seatNumber';
    update public.seats set is_occupied = true where id = seat_row.id;
    insert into public.booking_passengers
      (booking_id, seat_id, full_name, age, gender, passport_id, seat_number, travel_class, email, phone)
    values
      (booking_row.id, seat_row.id, trim(passenger ->> 'fullName'),
       coalesce(nullif(passenger ->> 'age', '')::integer, 30),
       coalesce(nullif(passenger ->> 'gender', ''), 'Male'),
       coalesce(passenger ->> 'passportId', ''), seat_row.seat_number, p_travel_class,
       coalesce(passenger ->> 'email', ''), coalesce(passenger ->> 'phone', ''));
    insert into public.boarding
      (booking_id, passenger_id, flight_id, seat_number, boarding_time)
    select booking_row.id, bp.id, p_flight_id, seat_row.seat_number, flight_row.departure_time - interval '45 minutes'
    from public.booking_passengers bp
    where bp.booking_id = booking_row.id and bp.seat_number = seat_row.seat_number;
  end loop;

  insert into public.payments (booking_id, transaction_id, payment_method, amount)
  values (booking_row.id, transaction_value, p_payment_method, total_value);
  insert into public.pnr_records (pnr, booking_id) values (pnr_value, booking_row.id);
  update public.flights set available_seats = available_seats - jsonb_array_length(p_passengers)
  where id = p_flight_id;

  return jsonb_build_object(
    'id', booking_row.id, 'pnr', pnr_value, 'flightId', p_flight_id,
    'flightNumber', flight_row.flight_number, 'travelClass', p_travel_class,
    'passengers', p_passengers,
    'fare', jsonb_build_object('baseFare', base_fare_value, 'taxAmount', tax_value,
      'discountAmount', discount_value, 'totalFare', total_value),
    'transactionId', transaction_value, 'paymentMethod', p_payment_method,
    'paymentStatus', 'PAID', 'bookingStatus', 'CONFIRMED'
  );
end;
$$;

create or replace function public.cancel_airline_booking(p_booking_id bigint)
returns void
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  booking_row public.bookings%rowtype;
  released_count integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select * into booking_row from public.bookings where id = p_booking_id for update;
  if not found then raise exception 'Booking not found'; end if;
  if booking_row.user_id <> auth.uid() and not public.is_airline_admin() then
    raise exception 'Not authorized to cancel this booking';
  end if;
  if booking_row.booking_status = 'CANCELLED' then raise exception 'Booking is already cancelled'; end if;

  update public.seats set is_occupied = false
  where id in (select seat_id from public.booking_passengers where booking_id = p_booking_id);
  get diagnostics released_count = row_count;
  update public.flights set available_seats = least(total_seats, available_seats + released_count)
  where id = booking_row.flight_id;
  update public.bookings set booking_status = 'CANCELLED', payment_status = 'REFUNDED', updated_at = now()
  where id = p_booking_id;
  update public.payments set payment_status = 'REFUNDED' where booking_id = p_booking_id;
  update public.pnr_records set is_active = false where booking_id = p_booking_id;
  update public.boarding set boarding_status = 'NOT_CHECKED_IN', check_in_status = 'NOT_CHECKED_IN',
    updated_at = now() where booking_id = p_booking_id;
end;
$$;

