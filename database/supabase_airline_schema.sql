create or replace function public.handle_new_airline_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  profile_name text;
  profile_phone text;
begin
  profile_name := coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1));
  profile_phone := coalesce(new.raw_user_meta_data ->> 'phone', '');
  insert into public.users (id, name, email, phone)
  values (new.id, profile_name, lower(new.email), profile_phone)
  on conflict (id) do nothing;
  insert into public.passengers (user_id, name, email, phone)
  values (new.id, profile_name, lower(new.email), profile_phone)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

create or replace function public.self_checkin_airline_booking(p_pnr text)
returns void
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  booking_row public.bookings%rowtype;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select * into booking_row from public.bookings
  where pnr = upper(trim(p_pnr)) and user_id = auth.uid()
  for update;
  if not found then raise exception 'Booking not found for this account'; end if;
  if booking_row.booking_status = 'CANCELLED' then raise exception 'Cannot check in for a cancelled booking'; end if;
  update public.boarding
  set check_in_status = 'CHECKED_IN', boarding_status = 'CHECKED_IN', updated_at = now()
  where booking_id = booking_row.id and boarding_status = 'NOT_CHECKED_IN';
end;
$$;

