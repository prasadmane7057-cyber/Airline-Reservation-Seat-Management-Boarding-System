create or replace function public.create_airline_booking(
  p_passenger_id bigint,
  p_flight_id bigint,
  p_seat_id bigint,
  p_travel_class text
)
returns public.bookings
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_owner_id uuid;
  v_seat public.seats%rowtype;
  v_booking public.bookings%rowtype;
  v_fare numeric(12, 2);
  v_pnr text;
begin
  if p_travel_class not in ('Economy', 'Business', 'First Class') then
    raise exception using errcode = 'P0001', message = 'Invalid travel class.';
  end if;

  select user_id into v_owner_id
  from public.passengers
  where id = p_passenger_id;
  if not found then
    raise exception using errcode = 'P0001', message = 'Passenger not found.';
  end if;
  if auth.role() <> 'service_role'
     and not public.is_airline_admin()
     and v_owner_id is distinct from auth.uid() then
    raise exception using errcode = 'P0001', message = 'Not authorized for this passenger.';
  end if;

  select * into v_seat
  from public.seats
  where id = p_seat_id and flight_id = p_flight_id
  for update;
  if not found then
    raise exception using errcode = 'P0001', message = 'Seat not found for this flight.';
  end if;
  if v_seat.seat_status <> 'AVAILABLE' then
    raise exception using errcode = 'P0001', message = 'Seat is not available.';
  end if;
  if v_seat.seat_class <> p_travel_class then
    raise exception using errcode = 'P0001', message = 'Seat class does not match travel class.';
  end if;

  v_fare := case p_travel_class
    when 'Economy' then 5000
    when 'Business' then 10000
    when 'First Class' then 20000
  end;
  v_pnr := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));

  insert into public.bookings
    (pnr, passenger_id, flight_id, seat_id, travel_class, fare, booking_status)
  values
    (v_pnr, p_passenger_id, p_flight_id, p_seat_id, p_travel_class, v_fare, 'CONFIRMED')
  returning * into v_booking;

  update public.seats
  set seat_status = 'BOOKED'
  where id = p_seat_id;
  return v_booking;
end;
$$;

create or replace function public.set_airline_seat_blocked(
  p_seat_id bigint,
  p_blocked boolean
)
returns public.seats
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_seat public.seats%rowtype;
begin
  if auth.role() <> 'service_role' and not public.is_airline_admin() then
    raise exception using errcode = 'P0001', message = 'Administrator privileges are required.';
  end if;

  select * into v_seat
  from public.seats
  where id = p_seat_id
  for update;
  if not found then
    raise exception using errcode = 'P0001', message = 'Seat not found.';
  end if;
  if p_blocked and v_seat.seat_status = 'BOOKED' then
    raise exception using errcode = 'P0001', message = 'A booked seat cannot be blocked.';
  end if;

  if v_seat.seat_status <> 'BOOKED' then
    update public.seats
    set seat_status = case when p_blocked then 'BLOCKED' else 'AVAILABLE' end
    where id = p_seat_id
    returning * into v_seat;
  end if;
  return v_seat;
end;
$$;

create or replace function public.cancel_airline_booking(p_booking_id bigint)
returns public.bookings
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_booking public.bookings%rowtype;
  v_owner_id uuid;
begin
  select * into v_booking
  from public.bookings
  where id = p_booking_id
  for update;
  if not found then
    raise exception using errcode = 'P0001', message = 'Booking not found.';
  end if;
  select user_id into v_owner_id
  from public.passengers
  where id = v_booking.passenger_id;
  if auth.role() <> 'service_role'
     and not public.is_airline_admin()
     and v_owner_id is distinct from auth.uid() then
    raise exception using errcode = 'P0001', message = 'Not authorized for this booking.';
  end if;
  if v_booking.booking_status not in ('CONFIRMED', 'WAITLISTED') then
    raise exception using errcode = 'P0001', message = 'Booking cannot be cancelled in its current status.';
  end if;

  if v_booking.booking_status = 'CONFIRMED' then
    update public.seats
    set seat_status = 'AVAILABLE'
    where id = v_booking.seat_id
      and seat_status = 'BOOKED';
  end if;
  update public.bookings
  set booking_status = 'CANCELLED'
  where id = p_booking_id
  returning * into v_booking;
  return v_booking;
end;
$$;

create or replace function public.board_airline_booking(
  p_pnr text,
  p_seat_id bigint
)
returns public.bookings
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_booking public.bookings%rowtype;
begin
  if auth.role() <> 'service_role' and not public.is_airline_admin() then
    raise exception using errcode = 'P0001', message = 'Administrator privileges are required to board passengers.';
  end if;

  select * into v_booking
  from public.bookings
  where pnr = upper(btrim(p_pnr))
    and seat_id = p_seat_id
    and booking_status = 'CONFIRMED'
    and checked_in_at is not null
  for update;
  if not found then
    raise exception using errcode = 'P0001', message = 'Booking, PNR, seat allocation, or check-in could not be verified.';
  end if;
  if not exists (
    select 1
    from public.seats
    where id = v_booking.seat_id
      and flight_id = v_booking.flight_id
      and seat_status = 'BOOKED'
  ) then
    raise exception using errcode = 'P0001', message = 'Booking seat allocation is invalid.';
  end if;

  update public.bookings
  set booking_status = 'BOARDED'
  where id = v_booking.id
  returning * into v_booking;
  return v_booking;
end;
$$;

