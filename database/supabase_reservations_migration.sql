-- Additive reservation schema for the existing Supabase project.
-- This migration does not alter flights or create airport, aircraft, or flight data.

do $$
declare
  flight_id_type text;
begin
  if to_regclass('public.flights') is null then
    raise exception 'Expected existing table public.flights; no changes were made.';
  end if;

  select format_type(atttypid, atttypmod)
  into flight_id_type
  from pg_attribute
  where attrelid = 'public.flights'::regclass
    and attname = 'id'
    and attnum > 0
    and not attisdropped;

  if flight_id_type is distinct from 'bigint' then
    raise exception 'Expected public.flights.id to be bigint, found %. No changes were made.',
      coalesce(flight_id_type, 'missing');
  end if;
end;
$$;

create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text unique,
  role text not null default 'passenger'
    check (role in ('passenger', 'admin', 'staff')),
  phone text not null default '',
  address text not null default '',
  dob date,
  status text not null default 'ACTIVE'
    check (status in ('ACTIVE', 'INACTIVE', 'SUSPENDED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.passengers (
  id bigint generated by default as identity primary key,
  user_id uuid unique references public.users(id) on delete set null,
  full_name text not null check (length(btrim(full_name)) between 1 and 160),
  email text not null check (length(btrim(email)) between 3 and 320),
  phone text not null default '' check (length(phone) <= 40),
  created_at timestamptz not null default now()
);

create table if not exists public.seats (
  id bigint generated by default as identity primary key,
  flight_id bigint not null references public.flights(id) on delete cascade,
  seat_number text not null
    check (seat_number ~ '^[0-9]{1,3}[A-Z]{1,2}$'),
  seat_class text not null
    check (seat_class in ('Economy', 'Business', 'First Class')),
  seat_status text not null default 'AVAILABLE'
    check (seat_status in ('AVAILABLE', 'BOOKED', 'BLOCKED')),
  created_at timestamptz not null default now(),
  unique (flight_id, seat_number),
  unique (id, flight_id)
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  pnr text not null unique check (pnr ~ '^[A-F0-9]{10}$'),
  passenger_id bigint not null
    references public.passengers(id) on delete restrict,
  flight_id bigint not null
    references public.flights(id) on delete restrict,
  seat_id bigint not null,
  travel_class text not null
    check (travel_class in ('Economy', 'Business', 'First Class')),
  fare numeric(12, 2) not null check (fare > 0),
  booking_status text not null default 'CONFIRMED'
    check (booking_status in ('CONFIRMED', 'WAITLISTED', 'CANCELLED', 'BOARDED')),
  checked_in_at timestamptz,
  booking_date timestamptz not null default now(),
  constraint bookings_seat_flight_fkey
    foreign key (seat_id, flight_id)
    references public.seats(id, flight_id) on delete restrict
);

create index if not exists passengers_user_id_idx
  on public.passengers(user_id);
create index if not exists bookings_passenger_date_idx
  on public.bookings(passenger_id, booking_date desc);
create index if not exists bookings_flight_status_idx
  on public.bookings(flight_id, booking_status);
create index if not exists seats_flight_status_idx
  on public.seats(flight_id, seat_status);
create unique index if not exists bookings_one_active_seat_idx
  on public.bookings(seat_id)
  where booking_status in ('CONFIRMED', 'BOARDED');
create unique index if not exists bookings_one_active_passenger_flight_idx
  on public.bookings(passenger_id, flight_id)
  where booking_status in ('CONFIRMED', 'WAITLISTED', 'BOARDED');

create or replace function public.is_airline_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.users
    where id = auth.uid()
      and role = 'admin'
      and status = 'ACTIVE'
  );
$$;

create or replace function public.handle_new_airline_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  profile_name text;
  profile_phone text;
begin
  profile_name := coalesce(
    nullif(btrim(new.raw_user_meta_data ->> 'name'), ''),
    nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
    'Passenger'
  );
  profile_phone := coalesce(new.raw_user_meta_data ->> 'phone', '');

  insert into public.users (id, name, email, phone)
  values (new.id, profile_name, lower(new.email), profile_phone)
  on conflict (id) do nothing;

  if new.email is not null then
    insert into public.passengers (user_id, full_name, email, phone)
    values (new.id, profile_name, lower(new.email), profile_phone)
    on conflict (user_id) do nothing;
  end if;
  return new;
end;
$$;

create or replace function public.update_airline_user_status(
  p_user_id uuid,
  p_status text
)
returns public.users
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_user public.users%rowtype;
begin
  if not public.is_airline_admin() then
    raise exception using errcode = 'P0001', message = 'Administrator privileges are required.';
  end if;
  if p_status not in ('ACTIVE', 'INACTIVE', 'SUSPENDED') then
    raise exception using errcode = 'P0001', message = 'Invalid account status.';
  end if;

  update public.users
  set status = p_status, updated_at = now()
  where id = p_user_id
  returning * into v_user;
  if not found then
    raise exception using errcode = 'P0001', message = 'User not found.';
  end if;
  return v_user;
end;
$$;

