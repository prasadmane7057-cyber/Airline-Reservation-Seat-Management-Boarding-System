create or replace function public.update_airline_booking_status(
  p_booking_id bigint,
  p_status text
)
returns public.bookings
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_booking public.bookings%rowtype;
  v_seat public.seats%rowtype;
begin
  if auth.role() <> 'service_role' and not public.is_airline_admin() then
    raise exception using errcode = 'P0001', message = 'Administrator privileges are required to update booking status.';
  end if;
  if p_status not in ('CONFIRMED', 'WAITLISTED', 'CANCELLED', 'BOARDED') then
    raise exception using errcode = 'P0001', message = 'Invalid booking status.';
  end if;

  select * into v_booking
  from public.bookings
  where id = p_booking_id
  for update;
  if not found then
    raise exception using errcode = 'P0001', message = 'Booking not found.';
  end if;
  if v_booking.booking_status = p_status then
    return v_booking;
  end if;
  if p_status = 'CANCELLED' then
    return public.cancel_airline_booking(p_booking_id);
  end if;
  if p_status = 'BOARDED' then
    return public.board_airline_booking(v_booking.pnr, v_booking.seat_id);
  end if;
  if v_booking.booking_status = 'CANCELLED' or v_booking.booking_status = 'BOARDED' then
    raise exception using errcode = 'P0001', message = 'Booking cannot transition from its current status.';
  end if;

  if p_status = 'WAITLISTED' then
    if v_booking.booking_status <> 'CONFIRMED' then
      raise exception using errcode = 'P0001', message = 'Only confirmed bookings can be waitlisted.';
    end if;
    update public.bookings
    set booking_status = 'WAITLISTED'
    where id = p_booking_id
    returning * into v_booking;
    update public.seats
    set seat_status = 'AVAILABLE'
    where id = v_booking.seat_id
      and seat_status = 'BOOKED';
    return v_booking;
  end if;

  if p_status = 'CONFIRMED' then
    if v_booking.booking_status <> 'WAITLISTED' then
      raise exception using errcode = 'P0001', message = 'Only waitlisted bookings can be confirmed.';
    end if;
    select * into v_seat
    from public.seats
    where id = v_booking.seat_id and flight_id = v_booking.flight_id
    for update;
    if not found or v_seat.seat_status <> 'AVAILABLE' then
      raise exception using errcode = 'P0001', message = 'The allocated seat is not available.';
    end if;
    update public.seats
    set seat_status = 'BOOKED'
    where id = v_booking.seat_id;
    update public.bookings
    set booking_status = 'CONFIRMED'
    where id = p_booking_id
    returning * into v_booking;
    return v_booking;
  end if;

  raise exception using errcode = 'P0001', message = 'Unsupported booking status transition.';
end;
$$;

